#!/usr/bin/env bash
# hive-chat.sh -- multi-session orchestrator for HAL/Copilot CLI chats.
#
# Each "chat" is a HAL-persona `copilot` process living in its own tmux window
# inside the `hive-console` session. This script is both:
#   * the LAUNCHER each chat window runs (`run` — persona refresh + relaunch loop)
#   * the CONTROLLER you drive from the CLI pane or console keybindings
#     (`new`, `resume`, `pick`, `ls`, `switch`, `kill`).
#
# Usage:
#   ./hive-chat.sh new [name]        # open a new HAL chat (optional session name)
#   ./hive-chat.sh resume [id|name]  # resume a past session (no arg -> picker)
#   ./hive-chat.sh pick              # interactive picker of past sessions
#   ./hive-chat.sh ls                # list open chat windows
#   ./hive-chat.sh switch [n]        # jump to chat window n (no arg -> tree)
#   ./hive-chat.sh kill <n>          # close chat window n
#   ./hive-chat.sh run               # INTERNAL: launch HAL in the current pane
#
# Env honored by `run` (set by the controller via `tmux new-window -e`):
#   HIVE_CHAT_NAME    -> copilot -n <name>   (name the new session)
#   HIVE_CHAT_RESUME  -> copilot -r <value>  (resume id/prefix/name)
#   HIVE_CHAT_CWD     -> working directory   (default: HIVE_DIR)
#   HIVE_CHAT_ARGS    -> extra raw copilot args (advanced)
# Shared with hive-console.sh:
#   HAL_PERSONA (persona source) · HIVE_CLI_CMD (copilot binary) · HIVE_CLI_DIR
set -euo pipefail

HIVE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SELF="$HIVE_DIR/hive-chat.sh"
SESSION="${HIVE_SESSION:-hive-console}"
PY="python3"

# ---- refresh the HAL persona into AGENTS.md (git root) --------------------
# Bare `copilot` skips Agent Wrapper, so it never loads the HAL persona. Copilot
# reads AGENTS.md from the git root (HIVE_DIR); refresh it from the canonical
# persona before every launch. The file is gitignored and self-heals on attach.
refresh_persona() {
  local persona="${HAL_PERSONA:-$HOME/.agents/context/0_hal_persona.md}"
  if [[ -f "$persona" ]]; then
    {
      echo "<!-- GENERATED by hive-chat.sh from $persona — do not edit; gitignored. -->"
      echo
      cat "$persona"
    } > "$HIVE_DIR/AGENTS.md"
  else
    echo "[hive-chat] HAL persona not found at $persona — chat will boot generic." >&2
  fi
}

# ---- INTERNAL: run one HAL chat in the current pane ----------------------
cmd_run() {
  refresh_persona
  local bin="${HIVE_CLI_CMD:-copilot}"
  local dir="${HIVE_CHAT_CWD:-${HIVE_CLI_DIR:-$HIVE_DIR}}"
  local -a args=()
  [[ -n "${HIVE_CHAT_NAME:-}"   ]] && args+=(-n "$HIVE_CHAT_NAME")
  [[ -n "${HIVE_CHAT_RESUME:-}" ]] && args+=(-r "$HIVE_CHAT_RESUME")
  # shellcheck disable=SC2206
  [[ -n "${HIVE_CHAT_ARGS:-}"   ]] && args+=(${HIVE_CHAT_ARGS})

  if ! command -v "${bin%% *}" >/dev/null 2>&1; then
    echo "[$bin not found — falling back to shell. Set HIVE_CLI_CMD]" >&2
    cd "$dir" && exec "${SHELL:-/bin/bash}"
  fi

  cd "$dir"
  # Give this window a stable, meaningful name so a HAL chat never masquerades
  # as a "bash" tab. tmux's automatic-rename would otherwise rewrite the name to
  # the shell wrapper's process, hiding that this is a distinct HAL session.
  if [[ -n "${TMUX:-}" ]]; then
    local wname="HAL:$(date +%H%M)"
    [[ -n "${HIVE_CHAT_NAME:-}"   ]] && wname="HAL:${HIVE_CHAT_NAME}"
    [[ -n "${HIVE_CHAT_RESUME:-}" ]] && wname="HAL:${HIVE_CHAT_RESUME:0:8}"
    tmux set-window-option automatic-rename off 2>/dev/null || true
    tmux set-window-option allow-rename       off 2>/dev/null || true
    tmux rename-window "$wname" 2>/dev/null || true
  fi
  # Relaunch loop so quitting `copilot` does NOT kill the pane/window:
  #   Enter    -> relaunch HAL      q+Enter / Ctrl-D -> drop to a shell
  while :; do
    "$bin" "${args[@]}"
    local ec=$?
    # After the first launch, drop resume/name so Enter starts a FRESH chat here.
    args=()
    printf '\n\033[33m[HAL exited (%s). Enter = new HAL chat  ·  q+Enter = shell]\033[0m ' "$ec"
    IFS= read -r ans || break
    [[ "$ans" == q ]] && break
  done
  echo "[shell — window preserved. Run: exec $SELF run   to bring HAL back]"
  exec "${SHELL:-/bin/bash}"
}

# ---- guard: controller subcommands need a tmux console -------------------
in_tmux() { [[ -n "${TMUX:-}" ]]; }

ensure_session() {
  if ! tmux has-session -t "$SESSION" 2>/dev/null; then
    echo "No '$SESSION' tmux session. Start it with: $HIVE_DIR/hive-console.sh" >&2
    return 1
  fi
}

# open a chat window; extra args are `tmux new-window -e VAR=val` pairs
open_window() {
  local title="$1"; shift
  local -a envs=()
  while [[ $# -gt 0 ]]; do envs+=(-e "$1"); shift; done
  if in_tmux; then
    tmux new-window -n "$title" "${envs[@]}" -c "$HIVE_DIR" "exec '$SELF' run"
  elif tmux has-session -t "$SESSION" 2>/dev/null; then
    tmux new-window -t "$SESSION" -n "$title" "${envs[@]}" -c "$HIVE_DIR" "exec '$SELF' run"
    tmux select-window -t "$SESSION:$title" 2>/dev/null || true
    echo "Opened chat window '$title' in session '$SESSION' (attach: tmux attach -t $SESSION)." >&2
  else
    # No console at all: just run inline, honoring the env we were handed.
    exec "$SELF" run
  fi
}

cmd_new() {
  local name="${1:-}"
  local title="chat:${name:-$(date +%H%M%S)}"
  if [[ -n "$name" ]]; then
    open_window "$title" "HIVE_CHAT_NAME=$name"
  else
    open_window "$title"
  fi
}

cmd_resume() {
  local val="${1:-}"
  [[ -z "$val" ]] && { cmd_pick; return; }
  local short="${val:0:8}"
  open_window "chat:$short" "HIVE_CHAT_RESUME=$val"
}

cmd_pick() {
  local sid rc
  # Capture stdout (selected id) and exit code without tripping `set -e`.
  sid="$("$PY" "$HIVE_DIR/hive_pick.py")" && rc=0 || rc=$?
  if [[ "$rc" == 10 ]]; then exec "$SELF" new; fi      # user chose "n" (new chat)
  [[ "$rc" != 0 ]] && return 0                          # quit / invalid / error
  [[ -z "$sid" ]] && { echo "No session selected." >&2; return 0; }
  exec "$SELF" resume "$sid"
}

cmd_ls() {
  ensure_session || return 1
  echo "Open chat windows in '$SESSION':"
  tmux list-windows -t "$SESSION" -F '  #{window_index}: #{window_name}#{?window_active, (active),}'
}

cmd_switch() {
  ensure_session || return 1
  local n="${1:-}"
  if [[ -z "$n" ]]; then
    in_tmux && exec tmux choose-tree -Zw
    echo "Attach first (tmux attach -t $SESSION), then: $SELF switch <n>" >&2
    cmd_ls
    return
  fi
  if in_tmux; then tmux select-window -t "$SESSION:$n"
  else tmux switch-client -t "$SESSION:$n" 2>/dev/null || echo "Not attached to $SESSION." >&2; fi
}

cmd_kill() {
  ensure_session || return 1
  local n="${1:?usage: hive-chat.sh kill <window-index>}"
  tmux kill-window -t "$SESSION:$n" && echo "Closed window $n."
}

usage() { sed -n '2,30p' "$SELF"; }

case "${1:-help}" in
  run)     cmd_run ;;
  new)     shift; cmd_new "$@" ;;
  resume)  shift; cmd_resume "$@" ;;
  pick)    cmd_pick ;;
  ls)      cmd_ls ;;
  switch)  shift; cmd_switch "$@" ;;
  kill)    shift; cmd_kill "$@" ;;
  help|-h|--help) usage ;;
  *) echo "unknown subcommand: $1" >&2; usage; exit 2 ;;
esac
