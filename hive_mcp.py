#!/usr/bin/env python3
"""Model Context Protocol (stdio) server for the HAL hive control plane.

Exposes the queue to any MCP client -- the Copilot CLI, the Copilot app, an
editor, or a `copilot` run *on a worker* -- by talking straight to the hive REST
API. It is deliberately transport-only: every decision (capability matching,
complexity->model, lease/merge policy) stays in ``hive_queue``/``queue_server``
so there is no second implementation to drift.

Read-only by default
--------------------
``queue_server`` splits auth two ways: ``HIVE_RO_TOKEN`` opens ``/status``,
``/metrics``, ``/logs/<id>`` and ``/task/<id>``; ``HIVE_TOKEN`` is needed for
anything that mutates the queue. This server honours that split rather than
papering over it -- with only a read token present the write tools are not even
advertised, so an agent cannot be tempted into queueing work it shouldn't. Set
``HIVE_MCP_ALLOW_WRITE=1`` *and* supply a control token to enable them.

That matters because the queue is, by design, a remote code execution service:
a task prompt is arbitrary instruction for an agent holding a shell on a lab
box. "Read-only unless explicitly told otherwise" is the safe default.

Zero dependencies (stdlib only) so the hive's install footprint is unchanged.

Environment
-----------
==========================  ====================================================
``HIVE_QUEUE_URL``          Control-plane base URL (default ``http://127.0.0.1:5001``).
``HIVE_RO_TOKEN``           Read-only bearer token. Falls back to the control token.
``HIVE_TOKEN``              Full-privilege bearer token.
``HIVE_MCP_ALLOW_WRITE``    ``1``/``true``/``yes`` to advertise add/cancel/requeue.
``HIVE_MCP_TIMEOUT_S``      Per-request timeout in seconds (default 15).
==========================  ====================================================

Tokens not in the environment are read from ``~/.hive/hive.env`` (the same file
the systemd units source), then ``~/.hive/worker.token``.

Wiring (``~/.copilot/mcp-config.json``)::

    "hive": {
      "type": "local",
      "command": "python3",
      "args": ["/home/afodor/hive/hive_mcp.py"],
      "tools": ["*"]
    }

Tools surface to the model as ``hive-status``, ``hive-task``, ... (the client
prefixes them with the config key).
"""

from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any

SERVER_NAME = "hive"
SERVER_VERSION = "1.0.0"
DEFAULT_PROTOCOL = "2024-11-05"

HIVE_ENV_FILE = Path.home() / ".hive" / "hive.env"
WORKER_TOKEN_FILE = Path.home() / ".hive" / "worker.token"

DEFAULT_URL = "http://127.0.0.1:5001"
DEFAULT_TIMEOUT_S = 15

# Statuses that mean "still moving". The queue keeps every task forever (169 and
# counting on the live box, most of them merged or capability-probe rows), so
# listing everything by default would bury the handful that actually need eyes.
# An allowlist rather than a terminal-state denylist: an unknown/new status is
# then quietly excluded from the default view instead of flooding it. Kept in
# step with the live set in hive_queue_active.STYLE.
ACTIVE_STATES = frozenset({
    "needs_attention", "running", "claimed", "verifying",
    "awaiting_review", "pending",
})

TASK_SUMMARY_FIELDS = (
    "id", "status", "kind", "title", "priority", "complexity", "model",
    "worker", "branch", "requires", "created_at", "heartbeat_at", "done_at",
    "error",
)

WORKER_SUMMARY_FIELDS = (
    "worker_id", "hostname", "lane", "host", "online", "status",
    "current_task", "caps", "last_seen", "age_s",
)

# lease_token is a live credential; the *_json blobs duplicate fields already
# returned in structured form.
TASK_DETAIL_OMIT = frozenset({"lease_token", "progress_json", "usage_json"})

PROMPT_PREVIEW_CHARS = 400
LOG_TAIL_CHARS = 4000


# ── config / auth ────────────────────────────────────────────────────────────

def _truthy(value: str | None) -> bool:
    return str(value or "").strip().lower() in ("1", "true", "yes", "on")


def _load_env_file() -> dict[str, str]:
    """Parse ~/.hive/hive.env (shell-style KEY=VALUE, # comments, optional quotes).

    Not a general shell parser: the file is generated by bootstrap.py and only
    ever holds flat assignments.
    """
    out: dict[str, str] = {}
    try:
        text = HIVE_ENV_FILE.read_text()
    except OSError:
        return out
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        value = value.strip().strip('"').strip("'")
        if value:
            out[key.strip()] = value
    return out


_ENV_FILE_CACHE: dict[str, str] | None = None


def _env(key: str) -> str:
    """Environment first, then ~/.hive/hive.env. Mirrors how the units resolve."""
    global _ENV_FILE_CACHE
    direct = os.environ.get(key)
    if direct and direct.strip():
        return direct.strip()
    if _ENV_FILE_CACHE is None:
        _ENV_FILE_CACHE = _load_env_file()
    return _ENV_FILE_CACHE.get(key, "").strip()


def control_token() -> str:
    tok = _env("HIVE_TOKEN")
    if tok:
        return tok
    try:
        return WORKER_TOKEN_FILE.read_text().strip()
    except OSError:
        return ""


def read_token() -> str:
    """Read-only token, falling back to the control token.

    The fallback is safe: a control token is a strict superset of read rights.
    It is one-way -- a read token is never used where control is required.
    """
    return _env("HIVE_RO_TOKEN") or control_token()


def base_url() -> str:
    return (_env("HIVE_QUEUE_URL") or DEFAULT_URL).rstrip("/")


def timeout_s() -> float:
    try:
        return float(_env("HIVE_MCP_TIMEOUT_S") or DEFAULT_TIMEOUT_S)
    except ValueError:
        return DEFAULT_TIMEOUT_S


def writes_enabled() -> bool:
    """Writes need an explicit opt-in *and* a control token: either alone is
    a misconfiguration, and failing closed beats surfacing tools that 401."""
    return _truthy(_env("HIVE_MCP_ALLOW_WRITE")) and bool(control_token())


# ── HTTP ─────────────────────────────────────────────────────────────────────

class HiveError(Exception):
    """A hive call failed in a way worth explaining to the model."""

    def __init__(self, message: str, hint: str = "") -> None:
        super().__init__(message)
        self.hint = hint


def _request(path: str, method: str = "GET", body: dict | None = None,
             *, control: bool = False, raw_text: bool = False) -> Any:
    token = control_token() if control else read_token()
    if not token:
        which = "HIVE_TOKEN" if control else "HIVE_RO_TOKEN/HIVE_TOKEN"
        raise HiveError(
            f"no hive {'control' if control else 'read'} token available",
            hint=f"set {which} in the environment or ~/.hive/hive.env",
        )

    url = base_url() + path
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Authorization", f"Bearer {token}")
    if data is not None:
        req.add_header("Content-Type", "application/json")

    try:
        with urllib.request.urlopen(req, timeout=timeout_s()) as resp:
            payload = resp.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace")[:400]
        try:
            detail = json.loads(detail).get("error", detail)
        except (ValueError, AttributeError):
            pass
        raise HiveError(f"hive {method} {path} -> HTTP {exc.code}: {detail}",
                        hint=_hint_for(exc.code, control)) from exc
    except urllib.error.URLError as exc:
        raise HiveError(
            f"cannot reach the hive at {base_url()}: {exc.reason}",
            hint="is queue_server running? check HIVE_QUEUE_URL and "
                 "`systemctl --user status hive-queue-server`",
        ) from exc

    if raw_text:
        return payload
    try:
        return json.loads(payload) if payload.strip() else {}
    except ValueError as exc:
        raise HiveError(f"hive returned non-JSON for {path}: {payload[:200]}") from exc


def _hint_for(code: int, control: bool) -> str:
    if code == 401:
        if control:
            return ("the control token was rejected; HIVE_TOKEN must match the "
                    "one queue_server was started with")
        return ("the read token was rejected; set HIVE_RO_TOKEN (or HIVE_TOKEN) "
                "to match queue_server")
    if code == 404:
        return "unknown id, or the task produced no log"
    if code == 409:
        return "a task with that id or branch already exists"
    return ""


# ── shaping ──────────────────────────────────────────────────────────────────

def _pick(row: dict, fields) -> dict:
    return {k: row[k] for k in fields if row.get(k) not in (None, "")}


def _truncate(text: Any, limit: int) -> Any:
    if not isinstance(text, str) or len(text) <= limit:
        return text
    return f"{text[:limit]} … [truncated, {len(text)} chars total]"


def _tail(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return f"… [earlier output trimmed, {len(text)} chars total]\n{text[-limit:]}"


# ── tools ────────────────────────────────────────────────────────────────────

def tool_status(args: dict) -> dict:
    """Queue counts, worker fleet, and tasks (in-flight only unless asked)."""
    snap = _request("/status")
    tasks = list(snap.get("tasks") or [])
    total = len(tasks)

    wanted = str(args.get("status") or "").strip().lower()
    if wanted:
        tasks = [t for t in tasks if str(t.get("status", "")).lower() == wanted]
    elif not args.get("all"):
        tasks = [t for t in tasks
                 if str(t.get("status", "")).lower() in ACTIVE_STATES]

    matched = len(tasks)
    limit = max(1, min(int(args.get("limit", 25) or 25), 200))
    tasks = tasks[:limit]

    out: dict[str, Any] = {
        "counts": snap.get("counts", {}),
        "tasks_total": total,
        "tasks_matched": matched,
        "tasks_shown": len(tasks),
        "tasks": [_pick(t, TASK_SUMMARY_FIELDS) for t in tasks],
    }
    if snap.get("usage_totals"):
        out["usage_totals"] = snap["usage_totals"]
    if args.get("include_workers", True):
        out["workers"] = [_pick(w, WORKER_SUMMARY_FIELDS)
                          for w in (snap.get("workers") or [])]
    return out


def tool_task(args: dict) -> dict:
    """One task in full, minus its live lease credential."""
    task_id = str(args.get("id") or "").strip()
    if not task_id:
        raise HiveError("id is required", hint="e.g. task-41a317e3")
    task = _request(f"/task/{urllib.parse.quote(task_id, safe='')}")
    out = {k: v for k, v in task.items() if k not in TASK_DETAIL_OMIT}
    if not args.get("include_prompt"):
        out["prompt"] = _truncate(out.get("prompt"), PROMPT_PREVIEW_CHARS)
    return out


def tool_logs(args: dict) -> dict:
    """Stored tail of a task's worker copilot log (plain text upstream)."""
    task_id = str(args.get("id") or "").strip()
    if not task_id:
        raise HiveError("id is required", hint="e.g. task-41a317e3")
    text = _request(f"/logs/{urllib.parse.quote(task_id, safe='')}", raw_text=True)
    limit = max(200, min(int(args.get("max_chars", LOG_TAIL_CHARS) or LOG_TAIL_CHARS),
                         20000))
    return {"id": task_id, "log_tail": _tail(text, limit)}


def tool_metrics(_args: dict) -> dict:
    """Fleet counters since server start, plus per-status task counts."""
    return _request("/metrics")


def tool_add(args: dict) -> dict:
    """Queue a task. A write: dispatches real work onto real workers."""
    prompt = str(args.get("prompt") or "").strip()
    if not prompt:
        raise HiveError("prompt is required")
    task_id = str(args.get("id") or "").strip() or f"task-{os.urandom(4).hex()}"

    body: dict[str, Any] = {
        "id": task_id,
        "prompt": prompt,
        "priority": int(args.get("priority", 5)),
        "kind": str(args.get("kind") or "work"),
    }
    requires = args.get("requires")
    if requires:
        # queue_server accepts a list or a space/comma string; send the string
        # form the dashboard's Add form already exercises.
        body["requires"] = (" ".join(requires) if isinstance(requires, list)
                            else str(requires))
    if args.get("complexity") is not None:
        body["complexity"] = max(1, min(int(args["complexity"]), 3))
    if args.get("model"):
        body["model"] = str(args["model"])
    if args.get("repo"):
        body["repo"] = str(args["repo"])

    _request("/add", method="POST", body=body, control=True)
    return {"queued": True, "id": task_id, "priority": body["priority"],
            "requires": body.get("requires"), "kind": body["kind"]}


def tool_cancel(args: dict) -> dict:
    """Cancel a task. A write."""
    task_id = str(args.get("id") or "").strip()
    if not task_id:
        # /cancel indexes task_id directly and would 500 on a missing key;
        # validate here so a slip is a clear message, not a server error.
        raise HiveError("id is required", hint="e.g. task-41a317e3")
    res = _request("/cancel", method="POST", body={"task_id": task_id}, control=True)
    return {"id": task_id, "cancelled": res.get("cancelled")}


def tool_requeue(args: dict) -> dict:
    """Re-enqueue a parked task (needs_attention/dead/cancelled). A write."""
    task_id = str(args.get("id") or "").strip()
    if not task_id:
        raise HiveError("id is required", hint="e.g. task-41a317e3")
    body = {"task_id": task_id,
            "reset_attempts": bool(args.get("reset_attempts", True))}
    res = _request("/requeue", method="POST", body=body, control=True)
    return {"id": task_id, "requeued": res.get("requeued")}


