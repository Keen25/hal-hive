def active_tools() -> list[dict]:
    return READ_TOOLS + (WRITE_TOOLS if writes_enabled() else [])


# ── JSON-RPC / MCP stdio ─────────────────────────────────────────────────────

def _log(message: str) -> None:
    """stdout is the JSON-RPC channel and must carry nothing else."""
    print(f"[hive-mcp] {message}", file=sys.stderr, flush=True)


def _send(message: dict) -> None:
    sys.stdout.write(json.dumps(message) + "\n")
    sys.stdout.flush()


def _result(req_id: Any, result: dict) -> None:
    _send({"jsonrpc": "2.0", "id": req_id, "result": result})


def _error(req_id: Any, code: int, message: str) -> None:
    _send({"jsonrpc": "2.0", "id": req_id, "error": {"code": code, "message": message}})


def _call_tool(params: dict) -> dict:
    name = params.get("name")
    args = params.get("arguments") or {}
    tool = next((t for t in active_tools() if t["name"] == name), None)

    if tool is None:
        known = ", ".join(t["name"] for t in active_tools())
        hidden = any(t["name"] == name for t in WRITE_TOOLS)
        detail = (f"'{name}' is a write tool and is disabled; set "
                  f"HIVE_MCP_ALLOW_WRITE=1 and provide HIVE_TOKEN to enable it"
                  if hidden else f"unknown tool '{name}'. Available: {known}")
        return {"content": [{"type": "text", "text": detail}], "isError": True}

    try:
        payload = tool["handler"](args)
        text = json.dumps(payload, indent=2, default=str)
    except HiveError as exc:
        text = str(exc) + (f"\nhint: {exc.hint}" if exc.hint else "")
        return {"content": [{"type": "text", "text": text}], "isError": True}
    except (ValueError, TypeError, KeyError) as exc:
        return {"content": [{"type": "text",
                             "text": f"bad arguments for {name}: {exc}"}],
                "isError": True}
    return {"content": [{"type": "text", "text": text}]}


def handle(message: dict) -> dict | None:
    """Return a response, or None for notifications (which take no reply)."""
    method = message.get("method")
    req_id = message.get("id")
    params = message.get("params") or {}
    is_notification = "id" not in message

    if method == "initialize":
        # Echo the client's protocol version when it offers one: this server only
        # uses the stable core (initialize / tools/list / tools/call), so there is
        # nothing to negotiate and agreeing avoids a spurious version mismatch.
        version = params.get("protocolVersion") or DEFAULT_PROTOCOL
        mode = "read+write" if writes_enabled() else "read-only"
        _log(f"initialize: {base_url()} ({mode}, {len(active_tools())} tools)")
        return {"protocolVersion": version,
                "capabilities": {"tools": {"listChanged": False}},
                "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION}}

    if method in ("notifications/initialized", "initialized"):
        return None

    if method == "ping":
        return {}

    if method == "tools/list":
        return {"tools": [{k: t[k] for k in ("name", "description", "inputSchema")}
                          for t in active_tools()]}

    if method == "tools/call":
        return _call_tool(params)

    if is_notification:
        return None
    raise LookupError(method or "<missing method>")


def main() -> int:
    _log(f"starting; queue={base_url()} "
         f"writes={'on' if writes_enabled() else 'off'}")
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            message = json.loads(line)
        except ValueError:
            _error(None, -32700, "parse error")
            continue

        req_id = message.get("id")
        try:
            response = handle(message)
        except LookupError as exc:
            _error(req_id, -32601, f"method not found: {exc}")
            continue
        except Exception as exc:  # never let one bad call kill the server
            _log(f"internal error: {exc!r}")
            _error(req_id, -32603, f"internal error: {exc}")
            continue

        if response is not None:
            _result(req_id, response)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(0)
